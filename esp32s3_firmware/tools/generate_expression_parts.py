#!/usr/bin/env python3
"""Generate firmware logical masks from the App's versioned, already placed catalog."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'ios/RinaBoard/Resources/expression_parts.json'
OUTPUT = ROOT / 'esp32s3_firmware/src/expression_parts_generated.h'
GROUPS = ('leye', 'reye', 'mouth', 'cheek')
TYPES = {'leye': 'eye_left', 'reye': 'eye_right', 'mouth': 'mouth', 'cheek': 'cheek'}


def generate(source: Path = SOURCE) -> str:
    raw = source.read_bytes()
    catalog = json.loads(raw)
    masks = {}
    for key, part in catalog['parts'].items():
        mask = bytes.fromhex(part['frame'])
        if len(mask) != 47 or mask[-1] & 0xfc:
            raise ValueError(f'invalid logical mask: {key}')
        masks[key] = mask
    part_ids = sorted(masks, key=int)
    lines = ['// Generated by tools/generate_expression_parts.py; do not edit.',
             f'// Source SHA-256: {hashlib.sha256(raw).hexdigest()}',
             '#pragma once', '#include <stdint.h>', '#include <stddef.h>',
             'namespace expression_parts {',
             f'inline constexpr char CATALOG[] = "{catalog["format"]}";',
             f'inline constexpr uint16_t VERSION = {catalog["version"]};',
             'inline constexpr size_t FRAME_SIZE = 47;',
             'struct Part { uint16_t id; uint8_t mask[FRAME_SIZE]; };',
             'inline constexpr Part PARTS[] = {']
    for part_id in part_ids:
        values = ','.join(f'0x{byte:02x}' for byte in masks[part_id])
        lines.append(f'    {{{part_id}, {{{values}}}}},')
    lines += ['};', 'struct Call { uint8_t group; uint16_t id; uint8_t partIndex; };',
              '// group: 0 left eye, 1 right eye, 2 mouth, 3 cheek. Includes 400 -> empty.',
              'inline constexpr Call CALLS[] = {']
    for group_index, group in enumerate(GROUPS):
        for call_id, part_id in sorted(catalog['call']['map'][group].items(), key=lambda item: int(item[0])):
            if catalog['parts'][part_id]['type'] not in ('empty', TYPES[group]):
                raise ValueError(f'wrong group: {group}/{call_id}')
            lines.append(f'    {{{group_index}, {int(call_id)}, {part_ids.index(part_id)}}},')
    lines += ['};', '} // namespace expression_parts', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated file is stale')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('expression_parts_generated.h is stale; run tools/generate_expression_parts.py')
        print('Firmware expression catalog matches App source (92 logical masks, stable call IDs).')
    else:
        OUTPUT.write_text(result)
